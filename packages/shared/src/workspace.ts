/** Marker stored in `businessEntities.moduleKey` for all workspace rows. */
export const WORKSPACE_MODULE_KEY = "workspace";

/** Entity type discriminators for workspace rows. */
export const WORKSPACE_ENTITY_TYPES = {
  channel: "channel",
  message: "message",
  member: "member",
  readState: "read_state",
} as const;

export type WorkspaceEntityType =
  (typeof WORKSPACE_ENTITY_TYPES)[keyof typeof WORKSPACE_ENTITY_TYPES];

/**
 * Compute the deterministic DM channel key for two members.
 *
 * The result is stable regardless of argument order so callers can use it for
 * idempotent lookups (`channels.findOrCreateDm`).
 */
export function computeDmKey(memberA: string, memberB: string): string {
  return [memberA, memberB].slice().sort().join("_");
}

